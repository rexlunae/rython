"""Shared helper for the numpy harnesses: enable stdpython features on a
crate generated by `rypip convert`.

rypip's stdpython dependency line has changed shape over time — first a
bare `stdpython = { path = "..." }`, later `{ path = "...",
default-features = false, features = ["std"] }`. The harnesses used to
match only the first shape with a regex, so after the change the numpy
backend features were silently never added: every `rayon`/`simd` run then
measured the runtime's loud "built without its feature" RuntimeError
instead of the backend. This merges into whatever features list is there,
and refuses to continue when it cannot find the line or the result lacks a
requested feature — a harness that silently measures the wrong build is
worse than one that stops.
"""

from __future__ import annotations

import re
from pathlib import Path

_DEP = re.compile(r"^stdpython = \{(?P<body>.*)\}$", re.M)
_FEATURES = re.compile(r"features = \[(?P<list>[^\]]*)\]")


def add_stdpython_features(toml: Path, features: list[str]) -> None:
    """Add `features` to the stdpython dependency in `toml`, in place."""
    if not features:
        return
    text = toml.read_text()
    dep = _DEP.search(text)
    if dep is None:
        raise RuntimeError(
            f"{toml}: no `stdpython = {{ ... }}` dependency line to add "
            f"{features} to; rypip's Cargo.toml shape changed again"
        )
    body = dep.group("body")
    existing = _FEATURES.search(body)
    if existing:
        have = [f.strip().strip('"') for f in existing.group("list").split(",") if f.strip()]
        merged = have + [f for f in features if f not in have]
        rendered = ", ".join(f'"{f}"' for f in merged)
        body = body.replace(existing.group(0), f"features = [{rendered}]", 1)
    else:
        rendered = ", ".join(f'"{f}"' for f in features)
        body = f"{body.rstrip()}, features = [{rendered}] "
    new_line = f"stdpython = {{{body}}}"
    missing = [f for f in features if f'"{f}"' not in new_line]
    if missing:
        raise RuntimeError(f"{toml}: failed to enable {missing} on: {new_line}")
    toml.write_text(text[: dep.start()] + new_line + text[dep.end():])
